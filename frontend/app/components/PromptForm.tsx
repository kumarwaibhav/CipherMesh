"use client";

import { useId, useState, type FormEvent, type KeyboardEvent } from "react";
import { Loader2, Send, Sparkles } from "lucide-react";
import { PROVIDER_OPTIONS, type TargetProvider } from "@/lib/api";
import { Card, focusRing, inputBase } from "./ui";

const GOOGLE_KEY_SAMPLE = "Maps quota error with key " + "AI" + "za" + "SyD3m0K3yF0rCipherMeshDemo0nly12345";

export const SAMPLES: ReadonlyArray<{ id: string; label: string; text: string }> = [
  { id: "clean", label: "Clean question", text: "Explain the difference between supervised and unsupervised learning." },
  {
    id: "pii",
    label: "PII — email + phone",
    text: "Summarize this support note for rahul.student@example.com and call +91 9876543210.",
  },
  {
    id: "india",
    label: "India identifiers (residency rule)",
    text: "Customer Aadhaar 2345 6789 0124 and PAN ABCPE1234F need a KYC summary.",
  },
  {
    id: "aws",
    label: "Cloud credential",
    text: "Debug this config: aws_access_key_id=AKIAIOSFODNN7EXAMPLE — why does auth fail?",
  },
  { id: "gkey", label: "Google API key", text: GOOGLE_KEY_SAMPLE },
  {
    id: "internal",
    label: "Internal URL (review)",
    text: "Summarize logs from https://payments.internal/debug generated by host 10.20.30.40.",
  },
  { id: "card", label: "Payment card", text: "Refund card 4111 1111 1111 1111 for the duplicate charge." },
];

const MAX_LEN = 65536;

export function PromptForm({
  busy,
  onSubmit,
}: {
  busy: boolean;
  onSubmit: (prompt: string, provider: TargetProvider) => void;
}) {
  const promptId = useId();
  const providerId = useId();
  const sampleId = useId();
  const hintId = useId();
  const [prompt, setPrompt] = useState("");
  const [provider, setProvider] = useState<TargetProvider>("auto");
  const [sample, setSample] = useState("");

  const trimmed = prompt.trim();
  const tooLong = prompt.length > MAX_LEN;
  const canSubmit = !busy && trimmed.length > 0 && !tooLong;

  const submit = () => {
    if (canSubmit) onSubmit(prompt, provider);
  };

  const handleSubmit = (e: FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    submit();
  };

  const handleKeyDown = (e: KeyboardEvent<HTMLTextAreaElement>) => {
    if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) {
      e.preventDefault();
      submit();
    }
  };

  return (
    <Card title="Inspect a prompt" icon={<Sparkles className="h-4 w-4" />} id="prompt-form">
      <form onSubmit={handleSubmit} className="flex flex-col gap-4" noValidate>
        <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
          <div className="min-w-0">
            <label htmlFor={sampleId} className="mb-1 block text-xs font-medium text-zinc-300">
              Samples
            </label>
            <select
              id={sampleId}
              value={sample}
              onChange={(e) => {
                const next = e.target.value;
                setSample(next);
                const found = SAMPLES.find((s) => s.id === next);
                if (found) setPrompt(found.text);
              }}
              className={inputBase}
            >
              <option value="">Choose a sample prompt…</option>
              {SAMPLES.map((s) => (
                <option key={s.id} value={s.id}>
                  {s.label}
                </option>
              ))}
            </select>
          </div>
          <div className="min-w-0">
            <label htmlFor={providerId} className="mb-1 block text-xs font-medium text-zinc-300">
              Target provider
            </label>
            <select
              id={providerId}
              value={provider}
              onChange={(e) => setProvider(e.target.value as TargetProvider)}
              className={inputBase}
            >
              {PROVIDER_OPTIONS.map((p) => (
                <option key={p.value} value={p.value}>
                  {p.label}
                </option>
              ))}
            </select>
          </div>
        </div>

        <div>
          <label htmlFor={promptId} className="mb-1 block text-xs font-medium text-zinc-300">
            Prompt
          </label>
          <textarea
            id={promptId}
            value={prompt}
            onChange={(e) => {
              setPrompt(e.target.value);
              setSample("");
            }}
            onKeyDown={handleKeyDown}
            rows={6}
            spellCheck={false}
            aria-describedby={hintId}
            aria-invalid={tooLong || undefined}
            placeholder="Paste the prompt your application is about to send to an LLM…"
            className={`${inputBase} min-h-[140px] resize-y font-mono leading-relaxed`}
          />
          <div id={hintId} className="mt-1 flex flex-wrap items-center justify-between gap-2 text-xs text-zinc-400">
            <span>
              <kbd className="rounded border border-zinc-700 bg-zinc-800 px-1 font-mono text-[11px]">Ctrl</kbd> /{" "}
              <kbd className="rounded border border-zinc-700 bg-zinc-800 px-1 font-mono text-[11px]">⌘</kbd> +{" "}
              <kbd className="rounded border border-zinc-700 bg-zinc-800 px-1 font-mono text-[11px]">Enter</kbd> to submit
            </span>
            <span className={tooLong ? "text-red-300" : undefined}>
              {prompt.length.toLocaleString()} / {MAX_LEN.toLocaleString()}
            </span>
          </div>
        </div>

        <div className="flex flex-wrap items-center justify-end gap-3">
          <button
            type="submit"
            disabled={!canSubmit}
            aria-busy={busy}
            className={`inline-flex items-center gap-2 rounded-lg bg-red-600 px-4 py-2 text-sm font-semibold text-white shadow-lg shadow-red-950/50 transition hover:bg-red-500 disabled:cursor-not-allowed disabled:bg-zinc-700 disabled:text-zinc-400 disabled:shadow-none ${focusRing}`}
          >
            {busy ? (
              <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
            ) : (
              <Send className="h-4 w-4" aria-hidden="true" />
            )}
            {busy ? "Inspecting…" : "Inspect & Route"}
          </button>
        </div>
      </form>
    </Card>
  );
}
