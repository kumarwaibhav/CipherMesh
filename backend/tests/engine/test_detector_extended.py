"""Detector upgrades: 1.2 parity, checksum validation, overlap merge, normalized views."""
import pytest

from ciphermesh.detector import detect, luhn_valid, redact, validate_custom_pattern, verhoeff_valid
from ciphermesh.evaluation import _synthetic_values
from ciphermesh.models import AgentState, Decision
from ciphermesh.policy import inspect_text

V = _synthetic_values()
STATE = AgentState(agent_id="t")


@pytest.mark.parametrize("text,category", [
    (f"token {V['OPENAI']}", "llm_api_key"),
    (f"token {V['GITHUB']}", "github_token"),
    (f"bot {V['SLACK']}", "slack_token"),
    (f"key {V['GOOGLE']}", "google_api_key"),
    (f"pay {V['STRIPE']}", "stripe_secret_key"),
    (f"session {V['JWT']}", "jwt_token"),
    (V["AZURE_KEY"], "azure_storage_key"),
    (V["GCP_KEY_ID"], "gcp_service_account_key"),
    (f"aws_secret_access_key={V['AWS_SECRET']}", "aws_secret_key"),
    (f"{V['PEM']}", "private_key_header"),
    ("redis://default:hunter22@cache.example.com:6379", "db_connection_string"),
    ("password=Correct-Horse-9", "password_assignment"),
], ids=lambda value: value if value.isidentifier() else "case")
def test_critical_formats_block(text, category):
    result = inspect_text(text, STATE)
    assert result.decision == Decision.BLOCK
    assert category in {f.category for f in result.findings}


def test_assignment_1_2_stream_parity():
    expected = {
        "Explain the difference between supervised and unsupervised learning.": Decision.ALLOW,
        "Summarize this support note for rahul.student@example.com and call +91 9876543210.": Decision.REDACT,
        "Debug this configuration: aws_access_key_id=AKIAIOSFODNN7EXAMPLE.": Decision.BLOCK,
        "Review this synthetic key header: -----BEGIN PRIVATE KEY----- now": Decision.BLOCK,
        "https://demo.blob.core.windows.net/logs?sv=demo&sig=abcdefghijklmnop1234567890": Decision.BLOCK,
        "Summarize logs from https://payments.internal/debug generated by host 10.20.30.40.": Decision.REVIEW,
    }
    for text, decision in expected.items():
        assert inspect_text(text, STATE).decision == decision, text


def test_checksums():
    assert luhn_valid("4111111111111111")
    assert not luhn_valid("1234567890123456")
    assert verhoeff_valid("234567890124")
    assert not verhoeff_valid("234567890123")


@pytest.mark.parametrize("text", [
    "order 1234 5678 9012 3456",          # Luhn-invalid digit run
    "matrix 2345 6789 0123",              # Verhoeff-invalid 12 digits
    "release version 2.4.1.7",            # version string, not an IP
    "password: ********",                 # masked value
    "timestamp 1712345678901",
])
def test_hard_negatives_allowed(text):
    assert inspect_text(text, STATE).decision == Decision.ALLOW


def test_overlap_merge_never_leaves_partial_secret():
    text = "conn mongodb://svc:pa55@user@example.com/db"
    findings = detect(text)
    sanitized = redact(text, findings)
    assert "pa55" not in sanitized and "example.com" not in sanitized
    assert len(findings) == 1 and findings[0].category == "db_connection_string"


def test_findings_never_carry_values():
    result = inspect_text(f"k {V['GITHUB']}", STATE)
    dumped = result.model_dump_json()
    assert V["GITHUB"] not in dumped


@pytest.mark.parametrize("text,decision", [
    ("key: A K I A I O S F O D N N 7 E X A M P L E", Decision.BLOCK),
    ("aws key base64 QUtJQUlPU0ZPRE5ON0VYQU1QTEU=", Decision.BLOCK),
    ("mail rahul [at] example [dot] com", Decision.REDACT),
])
def test_normalized_views_catch_simple_obfuscation(text, decision):
    result = inspect_text(text, STATE)
    assert result.decision == decision
    assert any(f.source.startswith("normalized:") for f in result.findings)


def test_custom_pattern_rejects_empty_match():
    assert validate_custom_pattern("a*") is not None
    assert validate_custom_pattern("PROJECT-[A-Z]{3}") is None


def test_safe_preview_present_for_block_and_review():
    block = inspect_text("AKIAIOSFODNN7EXAMPLE", STATE)
    review = inspect_text("see https://wiki.corp.local/x", STATE)
    assert block.sanitized_text is None and "[REDACTED:AWS_ACCESS_KEY]" in block.safe_preview
    assert review.sanitized_text is None and "[REDACTED:INTERNAL_URL]" in review.safe_preview
